#!/usr/bin/env python3
"""WTI Predicted Tweet — Posts tomorrow's WTI forecast to @DisneyStatsWhiz at 4 PM ET.

Reads content JSON from wilma-server (generated by Step 14 of the pipeline).
Renders Remotion video on wilma, SCPs it locally, uploads to Twitter with text.
Saves tweet_id to tweet_state.json keyed by reference_date for reply threading.
Posts confirmation to Discord #wti-pipeline.

Terminology:
  - tweet_date: when the tweet is posted (today)
  - reference_date: the date the statistics apply to (tomorrow for predicted)
"""

import json
import os
import subprocess
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import requests
from requests_oauthlib import OAuth1

# --- Configuration ---
SSH_HOST = "wilma@192.168.2.75"
CONTENT_DIR = str(Path.home() / "hazeydata" / "pipeline" / "content")
REMOTION_DIR = str(Path.home() / "hazeydata" / "remotion-tpcr")
DRY_RUN = os.environ.get("TPCR_TWEET_DRY_RUN", "1") != "0"  # default SAFE: dry run unless explicitly 0
DRY_OUT = Path(os.environ.get("TPCR_TWEET_DRY_OUT", str(Path.home() / "hazeydata" / "reports" / "wti_daily" / "dryrun")))
STATE_FILE = Path.home() / "hazeydata" / "reports" / "wti_daily" / "tweet_state.json"
DISCORD_CHANNEL_ID = "1479351574177513576"
DISCORD_API = "https://discord.com/api/v10"
TWITTER_API = "https://api.twitter.com/2/tweets"
TWITTER_UPLOAD_API = "https://upload.twitter.com/1.1/media/upload.json"


def load_env():
    """Load tokens from ~/.env."""
    env_file = Path.home() / ".env"
    if env_file.exists():
        for line in env_file.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                key, val = line.split("=", 1)
                if key.strip() not in os.environ:
                    os.environ[key.strip()] = val.strip().strip('"')


def get_twitter_auth():
    """Build OAuth1 auth for Twitter API v2."""
    return OAuth1(
        os.environ["TWITTER_CONSUMER_KEY"],
        os.environ["TWITTER_CONSUMER_SECRET"],
        os.environ["TWITTER_ACCESS_TOKEN"],
        os.environ["TWITTER_ACCESS_TOKEN_SECRET"],
    )


def ssh_read_file(path):
    """Read a local content file (Mini; formerly SSH to wilma)."""
    p = Path(path)
    return p.read_text().strip() if p.exists() else None


def render_video_on_wilma(target_date, content):
    """Render the Remotion video locally. Returns the mp4 Path, or None on failure."""
    remote_output = f"{REMOTION_DIR}/out/predicted-wti-{target_date}.mp4"
    data_path = f"{REMOTION_DIR}/public/daily-wti-data.json"

    park_emojis = {"MK": "\U0001f3f0", "EP": "\U0001f310", "HS": "\U0001f3ac", "AK": "\U0001f981"}
    parks_data = []
    for p in content.get("parks", []):
        wti = p.get("wti", 0)
        if wti < 15:
            label, emoji = "Low", "\U0001f48e"
        elif wti < 25:
            label, emoji = "Average", "\U0001f338"
        elif wti < 35:
            label, emoji = "Above Average", "\U0001f525"
        else:
            label, emoji = "High", "\U0001f534"
        parks_data.append({
            "parkCode": p.get("park_code", ""),
            "parkName": p.get("park_name", ""),
            "parkEmoji": park_emojis.get(p.get("park_code", ""), "\U0001f3a2"),
            "wtiScore": wti,
            "wtiEmoji": emoji,
            "wtiLabel": label,
            "headlinerRide": "Check the app!",
            "headlinerWait": 0,
            "bestRide": "Check the app!",
            "bestRideWait": 0,
        })

    from datetime import datetime
    dt = datetime.strptime(target_date, "%Y-%m-%d")
    date_display = dt.strftime("%B %d, %Y")

    remotion_data = json.dumps({
        "date": date_display,
        "dateISO": target_date,
        "mode": "predicted",
        "qualityGateStatus": "ready",
        "parks": parks_data,
    })

    print("Writing predicted data to Remotion...")
    Path(data_path).write_text(remotion_data)

    print("Rendering video locally...")
    render_cmd = (
        f"cd {REMOTION_DIR} && "
        f"npx remotion render DailyWTIAll '{remote_output}' --codec h264 --crf 18 --log=error"
    )
    result = subprocess.run(
        ["bash", "-lc", render_cmd],
        capture_output=True, text=True, timeout=600,
    )
    if result.returncode != 0:
        print(f"Render failed: {result.stderr}", file=sys.stderr)
        return None

    local_path = Path(remote_output)
    if not local_path.exists():
        print(f"Render produced no file at {local_path}", file=sys.stderr)
        return None

    print(f"Video rendered: {local_path} ({local_path.stat().st_size} bytes)")
    return local_path


def upload_media(video_path):
    if DRY_RUN:
        print('[dry-run] skip upload_media')
        return 'DRYRUN-MEDIA'
    """Upload video to Twitter via v1.1 chunked media upload. Returns media_id or None."""
    auth = get_twitter_auth()
    file_size = video_path.stat().st_size

    resp = requests.post(TWITTER_UPLOAD_API, auth=auth, data={
        "command": "INIT", "total_bytes": file_size,
        "media_type": "video/mp4", "media_category": "tweet_video",
    }, timeout=30)
    if resp.status_code not in (200, 201, 202):
        print(f"Media INIT failed: {resp.status_code} {resp.text}", file=sys.stderr)
        return None
    media_id = resp.json()["media_id_string"]

    with open(video_path, "rb") as f:
        resp = requests.post(TWITTER_UPLOAD_API, auth=auth, data={
            "command": "APPEND", "media_id": media_id, "segment_index": 0,
        }, files={"media": f}, timeout=60)
    if resp.status_code not in (200, 204):
        print(f"Media APPEND failed: {resp.status_code} {resp.text}", file=sys.stderr)
        return None

    resp = requests.post(TWITTER_UPLOAD_API, auth=auth, data={
        "command": "FINALIZE", "media_id": media_id,
    }, timeout=30)
    if resp.status_code not in (200, 201):
        print(f"Media FINALIZE failed: {resp.status_code} {resp.text}", file=sys.stderr)
        return None

    processing = resp.json().get("processing_info")
    elapsed = 0
    while processing and processing.get("state") != "succeeded":
        if processing.get("state") == "failed":
            print(f"Media processing failed: {processing}", file=sys.stderr)
            return None
        if elapsed > 60:
            print(f"Media processing timeout after {elapsed}s (state={processing.get('state')})", file=sys.stderr)
            return None
        wait = processing.get("check_after_secs", 5)
        print(f"Media processing... waiting {wait}s (state={processing.get('state')})")
        time.sleep(wait)
        elapsed += wait
        resp = requests.get(TWITTER_UPLOAD_API, auth=auth, params={
            "command": "STATUS", "media_id": media_id,
        }, timeout=15)
        processing = resp.json().get("processing_info")

    print(f"Media uploaded: {media_id}")
    return media_id


def load_content():
    """Load tomorrow's predicted content JSON from wilma."""
    tomorrow = (date.today() + timedelta(days=1)).isoformat()
    today = date.today().isoformat()

    for target_date in [tomorrow, today]:
        path = f"{CONTENT_DIR}/predicted_{target_date}.json"
        raw = ssh_read_file(path)
        if raw:
            try:
                data = json.loads(raw)
                if data.get("status") in ("ready", "released"):
                    return data
                print(f"Content for {target_date} is held: {data.get('held_reasons')}")
            except json.JSONDecodeError:
                print(f"Invalid JSON in {path}")

    return None


def format_tweet(content):
    """Format the predicted WTI content as a tweet."""
    target = content["target_date"]
    parks = content["parks"]
    parks_sorted = sorted(parks, key=lambda p: p["wti"])

    lines = [f"Walt Disney World Crowd Forecast \u2014 {target}"]
    lines.append("")
    for p in parks_sorted:
        wti = p["wti"]
        bar = crowd_bar(wti)
        lines.append(f"{bar} {p['park_name']}: {wti:.0f} min avg wait")
    lines.append("")
    lines.append("Lower WTI = shorter waits. Plan your day accordingly!")
    lines.append("#WDW #DisneyWorld #WaitTimes")

    return "\n".join(lines)


def crowd_bar(wti):
    if wti < 15:
        return "\U0001f7e2"
    elif wti < 25:
        return "\U0001f7e1"
    elif wti < 35:
        return "\U0001f7e0"
    else:
        return "\U0001f534"


def post_tweet(text, reply_to=None, media_id=None):
    if DRY_RUN:
        DRY_OUT.mkdir(parents=True, exist_ok=True)
        out = DRY_OUT / f'predicted_{date.today().isoformat()}.txt'
        out.write_text(text + (f'\n\n[reply_to={reply_to}] [media={media_id}]\n'))
        print(f'[dry-run] tweet NOT posted; text saved to {out}')
        return None
    auth = get_twitter_auth()
    payload = {"text": text}
    if reply_to:
        payload["reply"] = {"in_reply_to_tweet_id": reply_to}
    if media_id:
        payload["media"] = {"media_ids": [media_id]}

    resp = requests.post(TWITTER_API, json=payload, auth=auth, timeout=30)
    if resp.status_code in (200, 201):
        data = resp.json()
        tweet_id = data["data"]["id"]
        print(f"Tweet posted: {tweet_id}")
        return tweet_id
    else:
        print(f"Twitter API error {resp.status_code}: {resp.text}", file=sys.stderr)
        return None


def save_state(tweet_id, reference_date):
    if DRY_RUN:
        return
    """Save predicted tweet keyed by reference_date for observed reply threading.

    State structure:
      {
        "predicted": {
          "2026-03-31": {"tweet_id": "...", "posted_at": "..."},
          "2026-03-30": {"tweet_id": "...", "posted_at": "..."},
        },
        "last_predicted": {...}  // convenience pointer, backwards compat
      }
    """
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    state = {}
    if STATE_FILE.exists():
        try:
            state = json.loads(STATE_FILE.read_text())
        except json.JSONDecodeError:
            pass

    if "predicted" not in state:
        state["predicted"] = {}

    posted_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    # Key by reference_date so observed script can look up the right thread
    state["predicted"][reference_date] = {
        "tweet_id": tweet_id,
        "posted_at": posted_at,
    }

    # Keep last_predicted for backwards compat
    state["last_predicted"] = {
        "tweet_id": tweet_id,
        "reference_date": reference_date,
        "target_date": reference_date,
        "posted_at": posted_at,
    }

    # Prune entries older than 14 days
    cutoff = (date.today() - timedelta(days=14)).isoformat()
    state["predicted"] = {k: v for k, v in state["predicted"].items() if k >= cutoff}

    STATE_FILE.write_text(json.dumps(state, indent=2))
    print(f"State saved: reference_date={reference_date}, tweet_id={tweet_id}")


def post_discord(message):
    if DRY_RUN:
        print('[dry-run] skip post_discord')
        return None
    token = os.environ.get("DISCORD_BOT_TOKEN", "")
    if not token:
        return
    requests.post(
        f"{DISCORD_API}/channels/{DISCORD_CHANNEL_ID}/messages",
        json={"content": message},
        headers={"Authorization": f"Bot {token}", "Content-Type": "application/json"},
        timeout=15,
    )


def main():
    load_env()

    print(f"WTI Predicted Tweet \u2014 {date.today().isoformat()}")

    for key in ["TWITTER_CONSUMER_KEY", "TWITTER_CONSUMER_SECRET",
                "TWITTER_ACCESS_TOKEN", "TWITTER_ACCESS_TOKEN_SECRET"]:
        if not os.environ.get(key):
            print(f"ERROR: {key} not set", file=sys.stderr)
            sys.exit(1)

    content = load_content()
    if not content:
        print("No ready content found \u2014 skipping tweet")
        post_discord(":warning: **WTI Predicted Tweet** \u2014 No ready content found, tweet skipped")
        return

    reference_date = content["target_date"]

    # Idempotency guard (#468): skip if already posted for this reference_date
    if STATE_FILE.exists():
        try:
            existing = json.loads(STATE_FILE.read_text())
            if existing.get("predicted", {}).get(reference_date, {}).get("tweet_id"):
                print(f"Already posted predicted tweet for {reference_date}, exiting.")
                return
        except (json.JSONDecodeError, KeyError):
            pass
    tweet_text = format_tweet(content)
    print(f"\nTweet ({len(tweet_text)} chars, ref={reference_date}):\n{tweet_text}\n")

    media_id = None
    video_path = render_video_on_wilma(reference_date, content)
    if video_path:
        media_id = upload_media(video_path)
        if not media_id:
            print("WARNING: Video upload failed \u2014 posting text-only tweet")
    else:
        print("WARNING: Video render failed \u2014 posting text-only tweet")

    tweet_id = post_tweet(tweet_text, media_id=media_id)
    if DRY_RUN:
        print("Done (dry-run): nothing posted, no state saved.")
        return
    if not tweet_id:
        post_discord(":x: **WTI Predicted Tweet** \u2014 Twitter API error, tweet failed")
        sys.exit(1)

    save_state(tweet_id, reference_date)

    post_discord(
        f":white_check_mark: **WTI Predicted Tweet posted** \u2014 ref={reference_date}\n"
        f"https://x.com/DisneyStatsWhiz/status/{tweet_id}"
    )
    print("Done.")


if __name__ == "__main__":
    main()
