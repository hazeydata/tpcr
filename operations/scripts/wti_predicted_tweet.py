#!/usr/bin/env python3
"""WTI Predicted Tweet — Posts tomorrow's WTI forecast to @DisneyStatsWhiz at 4 PM ET.

Timing rule (Fred, Oct 26 2026): for reference day D this runs at 4 PM ET on D-1. It never posts about today.
Reads content JSON from wilma-server (generated by Step 14 of the pipeline) and wilma's wti.parquet,
builds the TPCR-TWEET-V2 forecast card + 7.1s MP4 locally (operations/tweet_v2/build_day.sh),
uploads the MP4 to X with alt text, and posts it with the tweet text.
--dry-run builds everything and posts nothing (no X/Discord calls, no state writes).
Saves tweet_id to tweet_state.json keyed by reference_date for reply threading.
Posts confirmation to Discord #wti-pipeline.

Terminology:
  - tweet_date: when the tweet is posted (today)
  - reference_date: the date the statistics apply to (tomorrow for predicted)
"""

import json
import os
import subprocess
import sys
import time
from datetime import date, timedelta
from pathlib import Path

import requests
from requests_oauthlib import OAuth1

import tweet_format
import tweet_note
import tweet_v2
from tweet_guard import enforce, preflight_legacy, status as guard_status

# --- Configuration ---
# Data host from env, no defaults: TPCR_SSH_HOST (ssh target), TPCR_CONTENT_DIR (Step 14 content dir there).
# tweet_v2.env_required raises '<NAME> is not set' when one is needed (see operations/tweet_v2/README.md).
STATE_FILE = Path.home() / "hazeydata" / "reports" / "wti_daily" / "tweet_state.json"
DISCORD_CHANNEL_ID = "1479351574177513576"
DISCORD_API = "https://discord.com/api/v10"
TWITTER_API = "https://api.twitter.com/2/tweets"
TWITTER_UPLOAD_API = "https://upload.twitter.com/1.1/media/upload.json"


def load_env():
    """Load tokens from ~/.env."""
    env_file = Path.home() / ".env"
    if env_file.exists():
        for line in env_file.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                key, val = line.split("=", 1)
                if key.strip() not in os.environ:
                    os.environ[key.strip()] = val.strip().strip('"')


def get_twitter_auth():
    """Build OAuth1 auth for Twitter API v2."""
    return OAuth1(
        os.environ["TWITTER_CONSUMER_KEY"],
        os.environ["TWITTER_CONSUMER_SECRET"],
        os.environ["TWITTER_ACCESS_TOKEN"],
        os.environ["TWITTER_ACCESS_TOKEN_SECRET"],
    )


def ssh_read_file(path):
    """Read a file from wilma-server via SSH."""
    result = subprocess.run(
        ["ssh", tweet_v2.env_required("TPCR_SSH_HOST"), f"cat '{path}'"],
        capture_output=True, text=True, timeout=15
    )
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def upload_media(video_path, alt_text=None):
    """Upload video to Twitter via v1.1 chunked media upload, then attach alt text. Returns media_id or None."""
    auth = get_twitter_auth()
    file_size = video_path.stat().st_size

    resp = requests.post(TWITTER_UPLOAD_API, auth=auth, data={
        "command": "INIT", "total_bytes": file_size,
        "media_type": "video/mp4", "media_category": "tweet_video",
    }, timeout=30)
    if resp.status_code not in (200, 201, 202):
        print(f"Media INIT failed: {resp.status_code} {resp.text}", file=sys.stderr)
        return None
    media_id = resp.json()["media_id_string"]

    with open(video_path, "rb") as f:
        resp = requests.post(TWITTER_UPLOAD_API, auth=auth, data={
            "command": "APPEND", "media_id": media_id, "segment_index": 0,
        }, files={"media": f}, timeout=60)
    if resp.status_code not in (200, 204):
        print(f"Media APPEND failed: {resp.status_code} {resp.text}", file=sys.stderr)
        return None

    resp = requests.post(TWITTER_UPLOAD_API, auth=auth, data={
        "command": "FINALIZE", "media_id": media_id,
    }, timeout=30)
    if resp.status_code not in (200, 201):
        print(f"Media FINALIZE failed: {resp.status_code} {resp.text}", file=sys.stderr)
        return None

    processing = resp.json().get("processing_info")
    elapsed = 0
    while processing and processing.get("state") != "succeeded":
        if processing.get("state") == "failed":
            print(f"Media processing failed: {processing}", file=sys.stderr)
            return None
        if elapsed > 60:
            print(f"Media processing timeout after {elapsed}s (state={processing.get('state')})", file=sys.stderr)
            return None
        wait = processing.get("check_after_secs", 5)
        print(f"Media processing... waiting {wait}s (state={processing.get('state')})")
        time.sleep(wait)
        elapsed += wait
        resp = requests.get(TWITTER_UPLOAD_API, auth=auth, params={
            "command": "STATUS", "media_id": media_id,
        }, timeout=15)
        processing = resp.json().get("processing_info")

    print(f"Media uploaded: {media_id}")
    # Fail closed: no tweet without alt text (metadata/create runs after FINALIZE, before the tweet).
    if not alt_text or not tweet_v2.set_alt_text(media_id, alt_text, auth, requests.post):
        print("ERROR: alt text not set on media; refusing to tweet", file=sys.stderr)
        return None
    return media_id


WDW_PARK_CODES = ("MK", "EP", "HS", "AK")


def _wdw_only(content):
    """Step 14 emits all parks; these tweets cover Walt Disney World only."""
    content = dict(content)
    content["parks"] = [p for p in content.get("parks", []) if p.get("park_code") in WDW_PARK_CODES]
    return content


def load_content(reference_date, content_dir=None):
    """Load D's predicted content JSON (raw text + parsed WDW-only dict). Only D, never today."""
    path = f"predicted_{reference_date}.json"
    raw = tweet_v2.read_content(path, content_dir, ssh_read_file)
    if raw:
        try:
            data = json.loads(raw)
            if data.get("status") in ("ready", "released"):
                return raw, _wdw_only(data)
            print(f"Content for {reference_date} is held: {data.get('held_reasons')}")
        except json.JSONDecodeError:
            print(f"Invalid JSON in {path}")
    return None, None


def format_tweet(content):
    """Format the predicted WTI content as a tweet."""
    target = content["target_date"]
    parks = content["parks"]
    parks_sorted = sorted(parks, key=lambda p: p["wti"])

    lines = [f"Walt Disney World Crowd Forecast \u2014 {target}"]
    lines.append("")
    for p in parks_sorted:
        wti = p["wti"]
        bar = crowd_bar(wti)
        lines.append(f"{bar} {p['park_name']}: {wti:.0f} min avg wait")
    lines.append("")
    lines.append("Lower WTI = shorter waits. Plan your day accordingly!")
    lines.append("#WDW #DisneyWorld #WaitTimes")

    return "\n".join(lines)


def crowd_bar(wti):
    if wti < 15:
        return "\U0001f7e2"
    elif wti < 25:
        return "\U0001f7e1"
    elif wti < 35:
        return "\U0001f7e0"
    else:
        return "\U0001f534"


def post_tweet(text, reply_to=None, media_id=None):
    auth = get_twitter_auth()
    payload = {"text": text}
    if reply_to:
        payload["reply"] = {"in_reply_to_tweet_id": reply_to}
    if media_id:
        payload["media"] = {"media_ids": [media_id]}

    resp = requests.post(TWITTER_API, json=payload, auth=auth, timeout=30)
    if resp.status_code in (200, 201):
        data = resp.json()
        tweet_id = data["data"]["id"]
        print(f"Tweet posted: {tweet_id}")
        return tweet_id
    else:
        print(f"Twitter API error {resp.status_code}: {resp.text}", file=sys.stderr)
        return None


def save_state(tweet_id, reference_date):
    """Save predicted tweet keyed by reference_date for observed reply threading.

    State structure:
      {
        "predicted": {
          "2026-03-31": {"tweet_id": "...", "posted_at": "..."},
          "2026-03-30": {"tweet_id": "...", "posted_at": "..."},
        },
        "last_predicted": {...}  // convenience pointer, backwards compat
      }
    """
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    with tweet_note.locked(STATE_FILE):
        state = {}
        if STATE_FILE.exists():
            try:
                state = json.loads(STATE_FILE.read_text())
            except json.JSONDecodeError:
                pass

        if "predicted" not in state:
            state["predicted"] = {}

        posted_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

        # Key by reference_date so observed script can look up the right thread
        state["predicted"][reference_date] = {
            "tweet_id": tweet_id,
            "posted_at": posted_at,
            "format": tweet_format.NEW,  # TPCR-TWEET-RESTYLE-CUTOVER: this script only posts the new format
        }

        # Keep last_predicted for backwards compat
        state["last_predicted"] = {
            "tweet_id": tweet_id,
            "reference_date": reference_date,
            "target_date": reference_date,
            "posted_at": posted_at,
        }

        # Prune entries older than 14 days
        cutoff = (date.today() - timedelta(days=14)).isoformat()
        state["predicted"] = {k: v for k, v in state["predicted"].items() if k >= cutoff}

        tweet_note._save(STATE_FILE, state)
    tweet_format.record(STATE_FILE, tweet_id, tweet_format.NEW, "predicted", reference_date, posted_at)
    print(f"State saved: reference_date={reference_date}, tweet_id={tweet_id}")


def post_discord(message):
    token = os.environ.get("DISCORD_BOT_TOKEN", "")
    if not token:
        return
    requests.post(
        f"{DISCORD_API}/channels/{DISCORD_CHANNEL_ID}/messages",
        json={"content": message},
        headers={"Authorization": f"Bot {token}", "Content-Type": "application/json"},
        timeout=15,
    )


def main(argv=None):
    args = tweet_v2.parse_args("predicted", argv)
    dry = args.dry_run
    if dry:
        tweet_v2.block_http_for_dry_run()
        print("DRY RUN: building only; nothing will be posted and no state will be written")
        guard = guard_status()
    else:
        load_env()
        enforce(preflight_legacy)
        guard = "enforced"

    reference_date = args.date or tweet_v2.default_reference_date("predicted")
    global STATE_FILE
    state_file = STATE_FILE = Path(args.state_file) if args.state_file else STATE_FILE
    print(f"WTI Predicted Tweet \u2014 {date.today().isoformat()} (ref={reference_date})")

    if not dry:
        for key in ["TWITTER_CONSUMER_KEY", "TWITTER_CONSUMER_SECRET",
                    "TWITTER_ACCESS_TOKEN", "TWITTER_ACCESS_TOKEN_SECRET"]:
            if not os.environ.get(key):
                print(f"ERROR: {key} not set", file=sys.stderr)
                sys.exit(1)

    if not dry and tweet_v2.now() < tweet_format.FIRST_NEW_RUN:
        # TPCR-TWEET-RESTYLE-CUTOVER: new-format originals start at FIRST_NEW_RUN (config/tweet_format.json).
        print(f"skipped_before_cutover ref={reference_date}: new-format originals start "
              f"{tweet_format.FIRST_NEW_RUN.isoformat()}; nothing posted")
        return 0

    blocked = None if dry else tweet_format.original_run_blocked(state_file)
    if blocked:
        print(f"ERROR skipped_bad_config ref={reference_date}: {blocked}; nothing posted", file=sys.stderr)
        print(f"skipped_bad_config ref={reference_date}: nothing posted")
        return 0

    if not tweet_v2.check_closures("predicted", reference_date, args.closures, print if dry else post_discord):
        sys.exit(1)  # R3: bad or missing closures.csv fails the run before any post

    raw, content = load_content(reference_date, args.content_dir)
    if not content:
        # AC 5a (closed-row R2): missing data is a skip, not a failure -> exit 0; alert after 2 days in a row
        tweet_v2.record_no_data("predicted", reference_date, state_file, post_discord if not dry else print, dry)
        return 0
    alert = print if dry else post_discord
    stale = tweet_v2.forecast_staleness(raw, reference_date)
    if stale:  # AC 16: old content never posts
        tweet_v2.record_stale("predicted", reference_date, stale, alert, state_file, dry)
        return 0
    tweet_v2.clear_no_data("predicted", state_file, dry)  # AC 5b: only a fresh data day ends the streak
    tweet_v2.check_park_hours("predicted", reference_date, args.park_hours, alert)  # AC 2a

    # Idempotency guard (#468): skip if already posted for this reference_date
    if state_file.exists():
        try:
            existing = json.loads(state_file.read_text())
            if existing.get("predicted", {}).get(reference_date, {}).get("tweet_id"):
                print(f"Already posted predicted tweet for {reference_date}, exiting.")
                return None
        except (json.JSONDecodeError, KeyError):
            pass
    work, tmp = tweet_v2.new_workdir(args.out)
    try:
        arts, build_error = {}, None
        try:
            history = tweet_v2.fetch_history(work, args.history)
            arts = tweet_v2.build(reference_date, work, history, raw, park_hours=args.park_hours, closures=args.closures)
        except Exception as e:  # noqa: BLE001 - any build failure means no card, so the bot stays silent
            build_error = str(e)
            print(f"WARNING: v2 card build failed \u2014 {build_error}", file=sys.stderr)
        if arts.get("skipped_all_closed"):  # closed-row R1: every park closed -> no forecast, no reply
            print(f"skipped_all_closed ref={reference_date}: every park closed; nothing posted")
            if dry:
                tweet_v2.write_manifest(work, {"would_post": False, "mode": "dry-run", "kind": "predicted",
                                               "reference_date": reference_date, "result": "skipped_all_closed"})
            return 0 if dry else None
        tweet_text = tweet_v2.post_text("predicted", arts)
        if arts.get("F") and not tweet_text and not build_error:
            build_error = "no approved copy for this case (edge copy v2); staying silent"
        f = arts.get("F") if tweet_text else None
        print(f"\nTweet ({len(tweet_text or '')} chars, ref={reference_date}):\n{tweet_text}\n")

        if dry:
            tweet_v2.write_manifest(work, {
                "would_post": bool(f), "mode": "dry-run", "kind": "predicted", "reference_date": reference_date,
                "posts_at": f"{(date.fromisoformat(reference_date) - timedelta(days=1)).isoformat()} 16:00 America/New_York",
                "tweet_text": tweet_text, "media": str(f["mp4"]) if f else None,
                "alt_text": f["alt"] if f else None, "build_error": build_error, "guard_status": guard,
                "would_save_state": f'predicted["{reference_date}"] in {state_file}',
            })
            return 0 if f else 1

        # Fred, Oct 26 2026: "Stay silent on missing-data days". No card = no tweet (edge copy v2 E1/E6/E7).
        if not f:
            print(f"SILENT: no forecast card for {reference_date} ({build_error}); nothing posted")
            post_discord(f":mute: **WTI Predicted Tweet** \u2014 ref={reference_date}: card not built, staying silent ({build_error})"[:1900])
            return None
        media_id = upload_media(f["mp4"], f["alt"])
        if not media_id:
            print("SILENT: video upload failed; nothing posted", file=sys.stderr)
            post_discord(f":x: **WTI Predicted Tweet** \u2014 ref={reference_date}: video upload failed, nothing posted")
            sys.exit(1)

        tweet_id = post_tweet(tweet_text, media_id=media_id)
        if not tweet_id:
            post_discord(":x: **WTI Predicted Tweet** \u2014 Twitter API error, tweet failed")
            sys.exit(1)

        save_state(tweet_id, reference_date)
        note = tweet_note.cap(tweet_note.note_lines(content["parks"]))
        if note:
            tweet_note.save_draft(STATE_FILE, reference_date, tweet_id, note)

        post_discord(
            f":white_check_mark: **WTI Predicted Tweet posted** \u2014 ref={reference_date}"
            "\n"
            f"https://x.com/DisneyStatsWhiz/status/{tweet_id}"
        )
        print("Done.")
    finally:
        tweet_v2.cleanup(tmp)


if __name__ == "__main__":
    sys.exit(main())
